# Example: greeting a user with variables

# Step 1 – store the user's name in a variable
name = "Alice"

# Step 2 – build a greeting message and store it in another variable
greeting = "Hello, " + name + "!"

# Step 3 – print the greeting
print(greeting)   # Hello, Alice!

